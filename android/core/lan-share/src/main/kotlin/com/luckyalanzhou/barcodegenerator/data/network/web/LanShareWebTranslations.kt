internal enum class LanShareWebLocale(val tag: String) {
    SIMPLIFIED_CHINESE("zh-Hans"),
    TRADITIONAL_CHINESE("zh-Hant"),
    ENGLISH("en"),
    JAPANESE("ja"),
    KOREAN("ko"),
    SPANISH("es");

    companion object {
        fun fromTag(tag: String): LanShareWebLocale =
            entries.firstOrNull { it.tag.equals(tag, ignoreCase = true) } ?: SIMPLIFIED_CHINESE
    }
}

